"""Pinned Fortress-only geometry for the G4 world and independent probes."""

TEST_BOX_CENTER = (2.0, 0.0)
TEST_BOX_HALF_SIZE = (0.5, 0.5)
WEST_ANCHOR_CENTER = (-2.0, 0.0)
WEST_ANCHOR_HALF_SIZE = (0.05, 2.0)

ROBOT_RADIUS = 0.22
MIN_ROBOT_CLEARANCE = 0.15
MAPPING_ROBOT_MARGIN = 0.30
# Lateral budget for AMCL/controller tracking error through the gate; the
# 0.05 m single-cell reserve of the former 0.84 m gate was not achievable.
NARROW_PASSAGE_LATERAL_BUDGET = 0.13

# Static cross-wall at x=4.0 leaves a sensor-mapped opening centered at y=-1.1.
NARROW_GATE_X = 4.0
NARROW_GATE_HALF_THICKNESS = 0.05
NARROW_PASSAGE_CENTER_Y = -1.10
NARROW_PASSAGE_HALF_WIDTH = round(
    ROBOT_RADIUS+MIN_ROBOT_CLEARANCE+NARROW_PASSAGE_LATERAL_BUDGET, 3)
NARROW_PASSAGE_LOW_Y = round(NARROW_PASSAGE_CENTER_Y-NARROW_PASSAGE_HALF_WIDTH, 3)
NARROW_PASSAGE_HIGH_Y = round(NARROW_PASSAGE_CENTER_Y+NARROW_PASSAGE_HALF_WIDTH, 3)
NARROW_PASSAGE_WIDTH = round(NARROW_PASSAGE_HIGH_Y-NARROW_PASSAGE_LOW_Y, 3)
NARROW_PASSAGE_GOAL = (4.8, NARROW_PASSAGE_CENTER_Y)
NARROW_WALL_Y_MIN = -20.0
NARROW_WALL_Y_MAX = 20.0
NARROW_PASSAGE_WALL_RECTS = (
		((NARROW_GATE_X, (NARROW_PASSAGE_HIGH_Y+NARROW_WALL_Y_MAX)/2),
		 (NARROW_GATE_HALF_THICKNESS,
			(NARROW_WALL_Y_MAX-NARROW_PASSAGE_HIGH_Y)/2)),
		((NARROW_GATE_X, (NARROW_WALL_Y_MIN+NARROW_PASSAGE_LOW_Y)/2),
		 (NARROW_GATE_HALF_THICKNESS,
			(NARROW_PASSAGE_LOW_Y-NARROW_WALL_Y_MIN)/2)),
)
